function text(value) {
  return String(value).replaceAll("\\", "\\\\").replaceAll("|", "\\|");
}

function sourceLink(source) {
  return `[${text(source.title)}](./REFERENCES.md#${source.id})`;
}

function url(value) {
  return `<${value}>`;
}

function termsLabel(terms) {
  const details = [terms.license, terms.url ? url(terms.url) : undefined].filter(
    Boolean,
  );
  return details.length ? `${terms.status} — ${details.join("; ")}` : terms.status;
}

function sourceSection(source) {
  const lines = [
    `<a id="${source.id}"></a>`,
    "",
    `## ${source.title}`,
    "",
    `- **Type:** ${source.type}`,
  ];
  if (source.creators?.length) {
    lines.push(
      `- **Creators:** ${source.creators.map((creator) => text(creator.name)).join(", ")}`,
    );
  }
  if (source.publisher) lines.push(`- **Publisher:** ${text(source.publisher)}`);
  if (source.datePublished) {
    lines.push(`- **Published:** ${source.datePublished}`);
  }
  if (source.dateAccessed) lines.push(`- **Accessed:** ${source.dateAccessed}`);
  if (source.url) lines.push(`- **Source:** ${url(source.url)}`);
  if (source.archiveUrl) lines.push(`- **Archive:** ${url(source.archiveUrl)}`);
  if (source.revision) lines.push(`- **Revision:** ${text(source.revision)}`);
  if (source.integrity) {
    lines.push(
      `- **Integrity:** \`${source.integrity.algorithm}:${source.integrity.value}\``,
    );
  }
  lines.push(`- **Terms:** ${termsLabel(source.terms)}`);
  if (source.terms.notes) lines.push(`- **Terms note:** ${text(source.terms.notes)}`);
  if (source.notes) lines.push(`- **Notes:** ${text(source.notes)}`);
  return lines.join("\n");
}

function evidenceLabel(evidence) {
  const locator = /^https?:\/\//.test(evidence.locator)
    ? url(evidence.locator)
    : `\`${evidence.locator}\``;
  return `${evidence.type}: ${locator}`;
}

function relationshipLine(relationship, source) {
  const details = [`relationship: ${relationship.type}`];
  if (relationship.confidence) details.push(`confidence: ${relationship.confidence}`);
  if (relationship.recordedAt) details.push(`recorded: ${relationship.recordedAt}`);

  const lines = [
    `- **${sourceLink(source)}** — ${text(relationship.contribution)}`,
    `  - ${details.join("; ")}`,
  ];
  if (relationship.evidence?.length) {
    lines.push(
      `  - Evidence: ${relationship.evidence.map(evidenceLabel).join("; ")}`,
    );
  }
  if (relationship.notes) lines.push(`  - Note: ${text(relationship.notes)}`);
  return lines.join("\n");
}

export function renderMarkdown(document) {
  const sources = [...document.sources].sort((left, right) =>
    left.title.localeCompare(right.title, "en"),
  );
  const sourceById = new Map(sources.map((source) => [source.id, source]));

  const references = [
    "<!-- Generated by Provenance. Edit provenance.yaml, not this file. -->",
    "",
    "# References",
    "",
    `Sources recorded for ${document.project.name}. Inclusion records provenance; it does not grant permission to reuse a source.`,
    "",
    ...sources.flatMap((source) => [sourceSection(source), ""]),
  ].join("\n");

  const byTarget = new Map();
  for (const relationship of document.relationships) {
    for (const target of relationship.targets) {
      const existing = byTarget.get(target) ?? [];
      existing.push(relationship);
      byTarget.set(target, existing);
    }
  }

  const influenceSections = [...byTarget.entries()]
    .sort(([left], [right]) => left.localeCompare(right, "en"))
    .flatMap(([target, relationships]) => [
      `## \`${target}\``,
      "",
      relationships
        .sort((left, right) => left.id.localeCompare(right.id, "en"))
        .map((relationship) =>
          relationshipLine(relationship, sourceById.get(relationship.source)),
        )
        .join("\n"),
      "",
    ]);

  const influences = [
    "<!-- Generated by Provenance. Edit provenance.yaml, not this file. -->",
    "",
    "# Influences",
    "",
    `Source-to-target relationships recorded for ${document.project.name}.`,
    "",
    ...influenceSections,
  ].join("\n");

  return { references, influences };
}
